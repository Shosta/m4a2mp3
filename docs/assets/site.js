function applyLanguage(language) {
  const selected = translations[language] ? language : "fr";
  const content = translations[selected];
  document.documentElement.lang = selected;
  document.title = content.pageTitle;
  document.querySelector('meta[name="description"]').content = content.pageDescription;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = content[element.dataset.i18n];
    if (value !== undefined) element.innerHTML = value;
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = content[element.dataset.i18nAlt];
    if (value !== undefined) element.alt = value;
  });
  document.querySelector(".language-picker").value = selected;
  document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    element.setAttribute("aria-label", content[element.dataset.i18nAriaLabel]);
  });
  try {
    localStorage.setItem("m4a2mp3-language", selected);
  } catch {
    return;
  }
}

let initialLanguage = "fr";
try {
  initialLanguage = localStorage.getItem("m4a2mp3-language") || "fr";
} catch {
  initialLanguage = "fr";
}
applyLanguage(initialLanguage);
document.querySelector(".language-picker").addEventListener("change", (event) => {
  applyLanguage(event.currentTarget.value);
});
